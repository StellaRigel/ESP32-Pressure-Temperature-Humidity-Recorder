static inline int uiFontIdx(uint16_t cp) {
  if (cp >= 0x20 && cp <= 0x7E) return (int)(cp - 0x20);
  for (int i = 0; i < UIFONT_EXT_COUNT; i++)
    if (uiFontExt[i] == cp) return 95 + i;
  return 0;
}
